import { randomUUID } from "node:crypto";
import { createServiceRoleClient } from "@/lib/supabase/server";
import { isSupabaseConfigured } from "@/lib/supabase/isConfigured";
import { readJson, writeJson } from "@/lib/devStore/fileStore";
import { toDateKey } from "@/lib/dates";
import type { DeliveryZone, SlotAvailability } from "@/lib/types/domain";

const PICKUP_WINDOWS: [string, string][] = [
  ["09:00", "12:00"],
  ["12:00", "15:00"],
  ["15:00", "18:00"],
  ["18:00", "21:00"],
];
const DELIVERY_WINDOWS: [string, string][] = [
  ["10:00", "12:00"],
  ["12:00", "14:00"],
  ["16:00", "18:00"],
  ["18:00", "20:00"],
];
const DAYS_AHEAD = 30;
const PICKUP_CAPACITY = 10;
const DELIVERY_CAPACITY = 3;
const HOLD_MINUTES = 10;

// Dev fallback mirroring supabase/seed.sql, so Buying Options works before
// a Supabase project exists — file-backed (see src/lib/devStore/fileStore)
// so the slot list generated by one request is still there on the next.
type MemSlot = {
  id: string;
  date: string;
  startTime: string;
  endTime: string;
  fulfilmentType: "pickup" | "delivery";
  zoneId: string;
  capacity: number;
  bookedCount: number;
};
type MemHold = { id: string; slotId: string; draftId: string; expiresAt: number };

export const MEMORY_ZONES: DeliveryZone[] = [
  { id: "zone-pickup", name: "Shop pickup", distanceBand: "pickup", deliveryFee: 0 },
  { id: "zone-nearby", name: "Nearby (College Road / Panchlaish)", distanceBand: "0-3km", deliveryFee: 180 },
  { id: "zone-mid", name: "Mid-range (Agrabad / Nasirabad)", distanceBand: "3-8km", deliveryFee: 300 },
  { id: "zone-far", name: "Far (rest of Chattogram)", distanceBand: "8km+", deliveryFee: 420 },
];

function dateStr(offsetDays: number): string {
  const d = new Date();
  d.setHours(0, 0, 0, 0);
  d.setDate(d.getDate() + offsetDays);
  return toDateKey(d);
}

function generateSlots(): MemSlot[] {
  const slots: MemSlot[] = [];
  const pickupZone = MEMORY_ZONES[0];
  const deliveryZones = MEMORY_ZONES.slice(1);

  for (let i = 0; i < DAYS_AHEAD; i++) {
    const date = dateStr(i);
    for (const [startTime, endTime] of PICKUP_WINDOWS) {
      slots.push({
        id: randomUUID(),
        date,
        startTime,
        endTime,
        fulfilmentType: "pickup",
        zoneId: pickupZone.id,
        capacity: PICKUP_CAPACITY,
        bookedCount: 0,
      });
    }
    for (const zone of deliveryZones) {
      for (const [startTime, endTime] of DELIVERY_WINDOWS) {
        slots.push({
          id: randomUUID(),
          date,
          startTime,
          endTime,
          fulfilmentType: "delivery",
          zoneId: zone.id,
          capacity: DELIVERY_CAPACITY,
          bookedCount: 0,
        });
      }
    }
  }

  // Same demo variety as seed.sql so the UI visibly shows low/full slots.
  const mark = (date: string, startTime: string, bookedCount: number) => {
    for (const s of slots) {
      if (s.date === date && s.startTime === startTime && s.fulfilmentType === "delivery") {
        s.bookedCount = bookedCount;
      }
    }
  };
  mark(dateStr(1), "12:00", DELIVERY_CAPACITY);
  mark(dateStr(1), "18:00", DELIVERY_CAPACITY - 1);
  mark(dateStr(2), "16:00", DELIVERY_CAPACITY);

  return slots;
}

async function loadSlots(): Promise<MemSlot[]> {
  const existing = await readJson<MemSlot[] | null>("slots", null);
  if (existing) return existing;
  const generated = generateSlots();
  await writeJson("slots", generated);
  return generated;
}

async function saveSlots(slots: MemSlot[]): Promise<void> {
  await writeJson("slots", slots);
}

async function loadHolds(): Promise<MemHold[]> {
  return readJson<MemHold[]>("slot-holds", []);
}

async function saveHolds(holds: MemHold[]): Promise<void> {
  await writeJson("slot-holds", holds);
}

/** Releases capacity from holds that were never converted to an order.
 * Mutates and returns the given slots array; persists both. */
async function releaseExpiredMemHolds(slots: MemSlot[]): Promise<MemSlot[]> {
  const holds = await loadHolds();
  const now = Date.now();
  const remaining: MemHold[] = [];
  let changed = false;

  for (const hold of holds) {
    if (hold.expiresAt < now) {
      changed = true;
      const slot = slots.find((s) => s.id === hold.slotId);
      if (slot) slot.bookedCount = Math.max(0, slot.bookedCount - 1);
    } else {
      remaining.push(hold);
    }
  }

  if (changed) {
    await saveHolds(remaining);
    await saveSlots(slots);
  }
  return slots;
}

function statusFor(remaining: number, capacity: number): SlotAvailability["status"] {
  if (remaining <= 0) return "full";
  if (remaining <= Math.max(1, Math.ceil(capacity * 0.3))) return "low";
  return "available";
}

export async function listZones(): Promise<DeliveryZone[]> {
  if (isSupabaseConfigured()) {
    const supabase = await createServiceRoleClient();
    const { data, error } = await supabase
      .from("delivery_zones")
      .select("id, name, distance_band, delivery_fee");
    if (error) throw error;
    return data.map((z) => ({
      id: z.id,
      name: z.name,
      distanceBand: z.distance_band,
      deliveryFee: Number(z.delivery_fee),
    }));
  }
  return MEMORY_ZONES;
}

export async function listAvailability(
  date: string,
  fulfilmentType: "pickup" | "delivery",
  zoneId?: string,
): Promise<SlotAvailability[]> {
  if (isSupabaseConfigured()) {
    const supabase = await createServiceRoleClient();
    await supabase.rpc("release_expired_holds");
    let query = supabase
      .from("delivery_slots")
      .select("id, date, start_time, end_time, fulfilment_type, zone_id, capacity, booked_count")
      .eq("date", date)
      .eq("fulfilment_type", fulfilmentType)
      .order("start_time");
    if (zoneId) query = query.eq("zone_id", zoneId);
    const { data, error } = await query;
    if (error) throw error;
    return data.map((s) => {
      const remaining = s.capacity - s.booked_count;
      return {
        slotId: s.id,
        date: s.date,
        startTime: s.start_time,
        endTime: s.end_time,
        fulfilmentType: s.fulfilment_type,
        zoneId: s.zone_id,
        capacity: s.capacity,
        remaining,
        status: statusFor(remaining, s.capacity),
      };
    });
  }

  const slots = await releaseExpiredMemHolds(await loadSlots());
  return slots
    .filter(
      (s) =>
        s.date === date &&
        s.fulfilmentType === fulfilmentType &&
        (!zoneId || s.zoneId === zoneId),
    )
    .sort((a, b) => a.startTime.localeCompare(b.startTime))
    .map((s) => {
      const remaining = s.capacity - s.bookedCount;
      return {
        slotId: s.id,
        date: s.date,
        startTime: s.startTime,
        endTime: s.endTime,
        fulfilmentType: s.fulfilmentType,
        zoneId: s.zoneId,
        capacity: s.capacity,
        remaining,
        status: statusFor(remaining, s.capacity),
      };
    });
}

export async function holdSlot(
  slotId: string,
  draftId: string,
): Promise<{ holdId: string; expiresAt: string }> {
  if (isSupabaseConfigured()) {
    const supabase = await createServiceRoleClient();
    const { data, error } = await supabase
      .rpc("hold_slot", {
        p_slot_id: slotId,
        p_draft_id: draftId,
        p_hold_minutes: HOLD_MINUTES,
      })
      .single();
    if (error) {
      if (error.message?.includes("slot_full")) throw new SlotFullError();
      throw error;
    }
    const row = data as { hold_id: string; expires_at: string };
    return { holdId: row.hold_id, expiresAt: row.expires_at };
  }

  return withHoldLock(async () => {
    const slots = await releaseExpiredMemHolds(await loadSlots());
    const slot = slots.find((s) => s.id === slotId);
    if (!slot) throw new Error("slot_not_found");
    if (slot.bookedCount >= slot.capacity) throw new SlotFullError();

    slot.bookedCount += 1;
    await saveSlots(slots);

    const expiresAt = Date.now() + HOLD_MINUTES * 60_000;
    const hold: MemHold = { id: randomUUID(), slotId, draftId, expiresAt };
    const holds = await loadHolds();
    holds.push(hold);
    await saveHolds(holds);

    return { holdId: hold.id, expiresAt: new Date(expiresAt).toISOString() };
  });
}

/** Converts a hold into a permanent booking at order finalization: just
 * deletes the slot_holds row. booked_count is already counted from when
 * the hold was created (see hold_slot() in the M4 migration) and stays
 * exactly as-is — this is what distinguishes a conversion from a release
 * (which decrements, see releaseExpiredMemHolds). */
export async function convertHold(slotId: string, draftId: string): Promise<void> {
  if (isSupabaseConfigured()) {
    const supabase = await createServiceRoleClient();
    const { error } = await supabase
      .from("slot_holds")
      .delete()
      .eq("slot_id", slotId)
      .eq("draft_order_id", draftId);
    if (error) throw error;
    return;
  }

  await withHoldLock(async () => {
    const holds = await loadHolds();
    await saveHolds(holds.filter((h) => !(h.slotId === slotId && h.draftId === draftId)));
  });
}

// Postgres `time` columns come back as "HH:MM:SS" — normalize to "HH:MM" so
// this always matches the dev fallback's format, since downstream
// consumers (OrderSummaryCard, AddToCalendarButton) parse it with a strict
// HH:MM regex.
export function formatSlotLabel(date: string, startTime: string, endTime: string): string {
  return `${date} ${startTime.slice(0, 5)}-${endTime.slice(0, 5)}`;
}

export async function getSlotLabel(slotId: string): Promise<string | null> {
  if (isSupabaseConfigured()) {
    const supabase = await createServiceRoleClient();
    const { data } = await supabase
      .from("delivery_slots")
      .select("date, start_time, end_time")
      .eq("id", slotId)
      .maybeSingle();
    if (!data) return null;
    return formatSlotLabel(data.date, data.start_time, data.end_time);
  }
  const slots = await loadSlots();
  const slot = slots.find((s) => s.id === slotId);
  return slot ? `${slot.date} ${slot.startTime}-${slot.endTime}` : null;
}

export class SlotFullError extends Error {
  constructor() {
    super("slot_full");
  }
}

// The dev fallback's read-modify-write against the JSON file isn't
// atomic the way Postgres's SELECT ... FOR UPDATE is — two concurrent
// holdSlot() calls could both read the same booked_count before either
// writes back, defeating the whole point of capacity locking. This mutex
// serializes them within this process (real concurrency safety still
// comes from Postgres once a project is connected; this only matters for
// exercising the race in local dev).
let holdMutex: Promise<unknown> = Promise.resolve();

export function withHoldLock<T>(fn: () => Promise<T>): Promise<T> {
  const result = holdMutex.then(fn, fn);
  holdMutex = result.catch(() => {});
  return result;
}
